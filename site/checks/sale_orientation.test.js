const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=__dirname+'/../',c={window:{}};
for(const f of ['data.js','route-matrix.js','book-ui.js'])vm.runInNewContext(fs.readFileSync(root+f,'utf8'),c);
const D=c.window.SCHEMA,S={goal:'book',scope:'promotion',format:'file',sample:false,salePlace:'donut',saleChosen:true,path:['telegram','tg-reply']};
c.S=S;c.render=()=>{};
const html=fs.readFileSync(root+'index.html','utf8');
vm.runInNewContext(html.slice(html.indexOf('function changeScope('),html.indexOf('function scrollToStep(')),c);
c.changeScope('sale');assert.equal(S.saleChosen,false,'An old Donat selection must not replace an unspecified destination');
const ui=c.window.BookUI.create({D,S,esc:String,curForm:()=>D.forms[0],saveBar:()=>''});
assert(!ui.renderStage().includes('aria-pressed="true"'));
assert(ui.renderStage().includes('Выберите, где размещено предложение'));
assert(!ui.summary().blocks.some(b=>b[0]==='Путь до оформления заказа'));
c.changeScope('promotion');assert.equal(S.path.join('/'),'telegram/tg-reply');
S.path.push('site');c.changeScope('sale');assert.equal(S.saleChosen,true);assert.equal(S.salePlace,'site');
assert(ui.renderStage().includes('Вы проверяете предложение: Свой сайт'));
assert(ui.renderStage().includes('Вы перешли из связки: Telegram'));
assert(ui.renderStage().includes('Вернуться к собранной связке'));
assert(!ui.renderStage().includes('Продажа: доступ по подписке'));
assert(html.indexOf('id="book-settings"')<html.indexOf('id="steps"'));
assert.equal((html.match(/id="book-settings"/g)||[]).length,1);
console.log('Sale orientation: stale destination ignored, chosen route destination retained, back navigation preserves path; format setting remains unique.');
